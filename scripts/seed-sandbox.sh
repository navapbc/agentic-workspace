#!/bin/sh
# Generate the FICTIONAL "Benefits Notices" sandbox workspace under reference/sandbox/.
#
# The sandbox is a fully populated, safe-to-share example a team can open in their harness
# to trial the setup. It is GENERATED (not hand-curated) so it doubles as a regression
# test of the templates and the support engine, and never drifts. Re-run after any
# template change; CI fails if the regenerated tree differs from the committed one.
#
# Usage: ./seed-sandbox.sh
#
# All content is fictional. No real client, program, system, repository, or person.

set -eu

