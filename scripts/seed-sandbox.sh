# Benefits Notices Workspace (SANDBOX)

> **FICTIONAL SANDBOX.** Every product, system, repository, and person here is made up.
> This exists so you can open a real, populated workspace and trial the kit before
> standing up your own. It is generated by `scripts/seed-sandbox.sh`; do not hand-edit.

"Benefits Notices" (BN) is a fictional product team that designs and ships outbound
beneficiary notices (eligibility determinations, appeal rights, renewals).

## Trial it in ~5 minutes

1. Open this folder in your agent tool (Codex/OpenCode/Cursor read `AGENTS.md`; Claude Code reads `CLAUDE.md`).
2. Ask your agent: "Read the root AGENTS.md and tell me the boundaries, the source ladder, and the vocabulary for this workspace."
3. Run the session-start probe: `./agentic-support/tools/workspace-doctor.sh`. With no
   declaration on your machine it exits 3 and tells you to run the `workspace-setup`
   skill — that fail-closed behavior *is* the feature. Ask your agent to run that skill
   and watch it interview you.
4. Ask "where does a delivery plan for the renewal notice go?" — the answer comes from
   `./agentic-support/tools/route-artifact.sh --type plan --area benefits-notices`,
   including the area's registered exception.
5. Ask "what does the notice-service repo do?" — the answer comes from a generated digest
   at `agentic-support/context-fabric/records/generated/repo-digests/`, with no git and no
   checkout.
6. Open `agentic-support/context-fabric/records/profiles/benefits-notices.json` — the
   shared facts an agent resolves from one line in a product-area `AGENTS.md`.
7. Read `agentic-support/skills/notice-change-brief/SKILL.md`, then ask your agent to run it.
8. Run the gate: `./agentic-support/validation/check-workspace.sh`.

## Layout

- `product-work/benefits-notices/` — the (fictional) product area, declaring its Context Fabric profile.
- `product-work/area-manifest.yaml` — the area registry, with one typed routing exception.
- `prototyping/` — empty; where spikes would go.
- `agentic-support/` — the support engine, plus one team skill, a small Context Fabric, and the two files a team authors itself.
- `docs/` — suggested lanes, with one sample plan and one sample solution.

## What a team authors vs. what installs verbatim

Everything under `agentic-support/` came from the kit unchanged **except** two files,
which are filled in here as examples of what your team writes:

- `agentic-support/CONCEPTS.md` — the workspace vocabulary.
- `agentic-support/docs/context-source-ladder.md` — which source to consult first.
EOF

